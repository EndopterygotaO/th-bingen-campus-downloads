export const languages = ['de', 'en', 'fr'];
let language = 'de';
try { const saved = globalThis.localStorage?.getItem('campus-language'); if (languages.includes(saved)) language = saved; } catch {}
export function getLanguage() { return language; }
export function setLanguage(value) {
  if (!languages.includes(value)) return false;
  language = value;
  try { globalThis.localStorage?.setItem('campus-language', value); } catch {}
  return true;
}
export function t(key, parameters = {}) {
  const message = messages[language][key] ?? key;
  return message.replace(/\{(\w+)\}/g, (match, name) => String(parameters[name] ?? match));
}
export function localizeText(value) {
  if (!value) return '';
  if (messages[language][value]) return t(value);
  return value.replace(/Gebäude/g, t('Gebäude')).replace(/Raum (?=[0-9])/g, t('Raum {room}', {room:''})).replace(/Erdgeschoss/g,t('Erdgeschoss')).replace(/1\. Obergeschoss/g,t('1. Obergeschoss')).replace(/2\. Obergeschoss/g,t('2. Obergeschoss'));
}
export function applyLanguage() {
  document.documentElement.lang = language;
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll('[data-i18n-aria]')) node.setAttribute('aria-label',t(node.dataset.i18nAria));
  for (const node of document.querySelectorAll('[data-i18n-placeholder]')) node.setAttribute('placeholder',t(node.dataset.i18nPlaceholder));
}
